# 任务：输出把"最低"和"最高"报反了，用断点确认排序后的真实顺序
# 操作清单：
#   1) 在 print("最低：", ...) 这一行设断点；
#   2) F5 启动，记录暂停时 speeds 的完整内容；
#   3) 分别按一次 F10，观察光标走了几行、变量有没有变化；
#   4) 只改一行代码把结果改对。

speeds = [62, 45, 78, 51]
speeds.sort()
print("升序车速：", speeds)
print("最低：", speeds[-1], "最高：", speeds[0])     # ← 断点设在这一行
avg = sum(speeds) / len(speeds)
print("平均车速：", round(avg, 1))
