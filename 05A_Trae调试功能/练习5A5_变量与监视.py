# ---------- 第 05A 节 · 练习 5A-5：变量的"范围"看错了 ----------
# 现象：京港澳有 3 个断面，输出却写"断面数：2"；京开只有 2 个，恰好也显示 2
# 任务：在 print(...) 设断点，把 len(road_flows) 与 len(flows) 同时加入「监视」，
#      看两个值的差别，说清"2"是哪个容器的长度
# 提示：监视表达式里可以写任何当前作用域内合法的表达式，不必改动源代码

road_flows = {"京港澳": [820, 1100, 760], "京开": [640, 720]}
for road in road_flows:
    flows = road_flows[road]
    print(road, "断面数：", len(road_flows), "| 合计：", sum(flows))   # ← 断点设在这一行
