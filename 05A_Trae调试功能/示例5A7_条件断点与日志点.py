# ---------- 第 05A 节 · 示例 5A-7：条件断点与日志点 ----------
# 对应知识点：5A.7 条件断点（只在满足条件时暂停）与日志点（打印但不打断）
# 操作：
#   1) 在 for 行设普通断点 → 会停 12 次，太吵；
#   2) 右键断点 →「编辑断点」→ 条件填 flows[i] > 1500，就只在超阈值那一次停下；
#   3) 把断点改成「日志点」，消息填 第 {i+1} 个时段：{flows[i]}，不暂停也能看到每一轮的值。

flows = [420, 510, 630, 700, 880, 950, 1100, 1650, 1320, 980, 760, 690]
for i in range(len(flows)):
    print("第", i + 1, "个时段：", flows[i], "辆/2h")

print()
for i in range(len(flows)):
    if flows[i] > 1500:
        print("超阈值时段：第", i + 1, "个，", flows[i], "辆/2h")
