# ---------- 第 05A 节 · 示例 5A-1：断点与启动调试 ----------
# 对应知识点：5A.1 行断点（F9）与启动调试（F5）
# 操作：在 total = total + f 这一行的行号左侧单击，出现红点即断点成功；
#      按 F5 启动调试，程序会在断点处暂停（该行高亮为黄色），
#      再按 F5「继续」，会在下一轮循环再次停在同一个断点上。

flows = [820, 1100, 760]
total = 0
for f in flows:
    total = total + f          # ← 断点设在这一行
print("三断面合计：", total)
print("平均流量：", round(total / len(flows), 1))
