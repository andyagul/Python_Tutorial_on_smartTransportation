PRED = ["事故", "拥堵", "事故", "施工", "通行正常"]
TRUTH = ["事故", "拥堵", "事故", "施工", "拥堵"]

hits = sum(1 for p, t in zip(PRED, TRUTH) if p == t)
print("样本数：", len(PRED))
print("命中数：", hits)
# 口径问题 1：直接拿样本数当「事件类型数」，没有按类别去重统计
print("事件类型数：", len(PRED))
print("分布： 无统计")
# 口径问题 2：准确率分母用了命中数，恒为 100%
print("准确率：", round(hits / hits * 100, 1), "%")
