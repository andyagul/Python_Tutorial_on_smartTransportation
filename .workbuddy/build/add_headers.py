def main():
    done, skipped = 0, []
    for rel, (title, kp, func) in HEADERS.items():
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            skipped.append(rel + "（文件不存在）")
            continue
        with open(path, encoding="utf-8") as f:
            text = f.read()
        if text.startswith("# ---------- 第"):
            skipped.append(rel + "（已有文件头）")
            continue
        header = (
            "# ---------- " + title + " ----------\n"
            "# 对应知识点：" + kp + "\n"
            "# 功能说明：" + func + "\n\n"
        )
        with open(path, "w", encoding="utf-8") as f:
            f.write(header + text)
        done += 1

    print("已补充文件头：%d 个" % done)
    for s in skipped:
        print("  跳过：", s)


if __name__ == "__main__":
    main()
