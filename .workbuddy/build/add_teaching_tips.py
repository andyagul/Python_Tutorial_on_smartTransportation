def main():
    done, skipped = 0, []
    for folder, block in TIPS.items():
        md = os.path.join(ROOT, folder, "案例与练习.md")
        with open(md, encoding="utf-8") as f:
            text = f.read()
        if "**教学提示（教师用）**" in text:
            skipped.append(folder + "（已存在）")
            continue
        if text.count(ANCHOR) != 1:
            skipped.append(folder + "（锚点异常）")
            continue
        text = text.replace(ANCHOR, "\n" + block + ANCHOR, 1)
        with open(md, "w", encoding="utf-8") as f:
            f.write(text)
        done += 1
    print("已插入教学提示：%d 章" % done)
    for s in skipped:
        print("  跳过：", s)


if __name__ == "__main__":
    main()
